const MajorDropDownButton1 = document.getElementById("MajorChordFormation1");
const ChordFormImage = document.getElementById("MajorChordImage");

ChordFormImage.style.display ="none";

MajorDropDownButton1.addEventListener("click", (event) => {
    if(ChordFormImage.style.display == "none"){
        ChordFormImage.style.display ="block";
    } else {
        ChordFormImage.style.display ="none";
    }
});

